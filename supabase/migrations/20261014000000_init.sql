-- Daedalus schema. Every row belongs to one user; RLS lets a signed-in user read only their own
-- rows. Writes to runs/spans/messages/credentials happen on the server with the service role,
-- which bypasses RLS, so server code always filters by user_id explicitly.

create extension if not exists pgcrypto;

-- Profiles -----------------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  avatar_url text,
  active_provider text,
  active_model text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name, avatar_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'user_name', split_part(new.email, '@', 1)),
    new.raw_user_meta_data ->> 'avatar_url'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Bring-your-own-key credentials. Ciphertext is AES-256-GCM, produced by the app; the key that
-- encrypts it lives in the app's environment, never in the database. No client access at all.
create table public.credentials (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  provider text not null check (provider in ('nvidia', 'anthropic', 'openai', 'deepseek')),
  key_ciphertext text not null,
  key_last4 text not null,
  default_model text not null,
  status text not null default 'valid' check (status in ('valid', 'invalid')),
  last_validated_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, provider)
);

-- Projects -----------------------------------------------------------------------------------
create table public.projects (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null,
  description text,
  status text not null default 'new' check (status in ('new', 'provisioning', 'ready', 'building', 'error')),
  template text not null default 'vite-react',
  sandbox_provider text,
  sandbox_id text,
  preview_url text,
  preview_port int not null default 5173,
  preview_status text not null default 'stopped',
  github_repo text,
  github_branch text not null default 'main',
  github_last_sha text,
  deploy_url text,
  last_run_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index projects_user_idx on public.projects (user_id, updated_at desc);

-- Chat messages, stored as AI SDK UIMessage parts (the source of truth for the conversation).
create table public.messages (
  id text primary key,
  project_id uuid not null references public.projects (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null check (role in ('user', 'assistant', 'system')),
  parts jsonb not null,
  metadata jsonb,
  run_id uuid,
  created_at timestamptz not null default now()
);
create index messages_project_idx on public.messages (project_id, created_at);

-- Agent runs: one per user turn. workflow_run_id links to the durable workflow.
create table public.runs (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  workflow_run_id text,
  mode text not null default 'build' check (mode in ('plan', 'build')),
  provider text not null,
  model text not null,
  status text not null default 'queued' check (status in ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
  error text,
  summary text,
  input_tokens bigint not null default 0,
  output_tokens bigint not null default 0,
  llm_calls int not null default 0,
  tool_calls int not null default 0,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);
create index runs_project_idx on public.runs (project_id, started_at desc);

-- Trace spans. A run is a tree: run -> agent steps -> llm calls and tool calls -> sub-agents ->
-- their own llm and tool calls. ids are generated by the app so children can be written
-- before or after their parent finishes.
create table public.spans (
  id uuid primary key,
  run_id uuid not null references public.runs (id) on delete cascade,
  parent_id uuid,
  project_id uuid not null references public.projects (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null check (kind in ('run', 'llm', 'tool', 'subagent', 'sandbox', 'verify', 'system')),
  name text not null,
  status text not null default 'running' check (status in ('running', 'ok', 'error', 'cancelled')),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  duration_ms int,
  attrs jsonb not null default '{}'::jsonb,
  input jsonb,
  output jsonb,
  error text
);
create index spans_run_idx on public.spans (run_id, started_at);

-- Checkpoints: git commits the harness makes in the sandbox after each run with changes.
create table public.checkpoints (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  run_id uuid,
  sha text not null,
  message text not null,
  files_changed int not null default 0,
  created_at timestamptz not null default now()
);
create index checkpoints_project_idx on public.checkpoints (project_id, created_at desc);

-- Deployments of user apps.
create table public.deployments (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  provider text not null default 'vercel',
  external_id text,
  url text,
  status text not null default 'building' check (status in ('building', 'ready', 'error', 'cancelled')),
  error text,
  checkpoint_sha text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index deployments_project_idx on public.deployments (project_id, created_at desc);

-- GitHub connection (OAuth token, encrypted like credentials). No client access.
create table public.github_connections (
  user_id uuid primary key references auth.users (id) on delete cascade,
  github_login text not null,
  token_ciphertext text not null,
  scopes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Runtime errors reported by the preview bridge script inside the user's app.
create table public.preview_errors (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null default 'error',
  message text not null,
  stack text,
  url text,
  created_at timestamptz not null default now()
);
create index preview_errors_project_idx on public.preview_errors (project_id, created_at desc);

-- updated_at triggers ----------------------------------------------------------------------------
create function public.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_touch before update on public.profiles for each row execute function public.touch_updated_at();
create trigger credentials_touch before update on public.credentials for each row execute function public.touch_updated_at();
create trigger projects_touch before update on public.projects for each row execute function public.touch_updated_at();
create trigger deployments_touch before update on public.deployments for each row execute function public.touch_updated_at();
create trigger github_touch before update on public.github_connections for each row execute function public.touch_updated_at();

