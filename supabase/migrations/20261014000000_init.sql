create policy "own profile" on public.profiles for select to authenticated using ((select auth.uid()) = id);
create policy "update own profile" on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create policy "own projects" on public.projects for select to authenticated using ((select auth.uid()) = user_id);
create policy "rename own projects" on public.projects for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "delete own projects" on public.projects for delete to authenticated using ((select auth.uid()) = user_id);

create policy "own messages" on public.messages for select to authenticated using ((select auth.uid()) = user_id);
create policy "own runs" on public.runs for select to authenticated using ((select auth.uid()) = user_id);
create policy "own spans" on public.spans for select to authenticated using ((select auth.uid()) = user_id);
create policy "own checkpoints" on public.checkpoints for select to authenticated using ((select auth.uid()) = user_id);
create policy "own deployments" on public.deployments for select to authenticated using ((select auth.uid()) = user_id);
create policy "own preview errors" on public.preview_errors for select to authenticated using ((select auth.uid()) = user_id);
-- credentials and github_connections: no policies, so only the service role can touch them.

-- The secrets never leave the server, even to their owner.
revoke all on public.credentials from anon, authenticated;
revoke all on public.github_connections from anon, authenticated;

-- Live updates for the workspace (RLS still applies to realtime subscribers).
alter publication supabase_realtime add table public.runs, public.spans, public.projects, public.checkpoints, public.deployments;
