// Embeds sandbox-template/ into a TypeScript module so serverless bundles always carry it.
// Runs before `dev` and `build`. Output: src/lib/sandbox/template-files.ts
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../sandbox-template/", import.meta.url));
const skip = new Set(["node_modules", "dist", ".git"]);
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    if (skip.has(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push({ path: relative(root, p), content: readFileSync(p, "utf8") });
  }
})(root);
files.sort((a, b) => a.path.localeCompare(b.path));
const out = `// Generated by scripts/embed-template.mjs from sandbox-template/. Do not edit.
export const TEMPLATE_FILES: ReadonlyArray<{ path: string; content: string }> = ${JSON.stringify(files, null, 2)};
`;
writeFileSync(new URL("../src/lib/sandbox/template-files.ts", import.meta.url), out);
console.log(`embedded ${files.length} template files`);
